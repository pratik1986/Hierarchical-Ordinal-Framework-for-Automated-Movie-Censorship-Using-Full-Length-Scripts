    • Moves all verified movie script files.
    • Reports missing files.
    • Preserves the manually curated dataset.

Inputs:
    - Source directory containing all downloaded scripts.
    - List of manually verified filenames.

Outputs:
    - Curated movie script dataset.

Author:
    Pratik N. Kalamkar
===============================================================================
